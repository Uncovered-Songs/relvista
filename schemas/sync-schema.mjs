#!/usr/bin/env node
// Copies the canonical schemas/layout.schema.json into @relvista/core:
//   packages/core/layout.schema.json          (published file, `@relvista/core/layout.schema.json`)
//   packages/core/src/layout/schema.generated.ts (the same schema as a TS module, used by parseLayout)
// Run with --check to fail instead of writing when a copy is out of date.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const source = join(here, 'layout.schema.json');
const jsonTarget = join(root, 'packages/core/layout.schema.json');
const tsTarget = join(root, 'packages/core/src/layout/schema.generated.ts');

const raw = readFileSync(source, 'utf8');
const schema = JSON.parse(raw); // fail fast on invalid JSON

const ts =
  '// GENERATED by schemas/sync-schema.mjs from schemas/layout.schema.json. Do not edit.\n' +
  `export const layoutSchema = ${JSON.stringify(schema, null, 2)} as const;\n`;

const check = process.argv.includes('--check');
let stale = 0;
for (const [target, content] of [
  [jsonTarget, raw],
  [tsTarget, ts],
]) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.error(`out of date: ${relative(root, target)} (run sync-schema)`);
    stale++;
  } else {
    writeFileSync(target, content);
    console.log(`wrote ${relative(root, target)}`);
  }
}
if (stale) process.exit(1);
