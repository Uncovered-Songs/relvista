/** Dialect guess for opened / dropped .sql files (design phase3 §6.3). */
import { readdirSync, readFileSync } from 'node:fs';
import { exporter } from '@dbml/core';
import { compileDbml } from '@relvista/core';
import { describe, expect, it } from 'vitest';
import { guessDialect, isSqlName, stripSqlNoise } from '../src/sql/dialect.js';
import { exportSnowflake } from '../src/sql/snowflake.js';

const EXAMPLES = new URL('../../../examples/', import.meta.url);
const exampleFiles = readdirSync(EXAMPLES).filter((f) => f.endsWith('.dbml'));
/**
 * Oracle exports with nothing Oracle-only in them (no identity column, no schema user, only
 * portable types): guessing PostgreSQL is right there, and its importer reads them.
 */
const PORTABLE_ORACLE = new Set([
  '09-table-partials.dbml',
  '13-project-settings-and-metadata.dbml',
]);

describe('guessDialect', () => {
  it.each([
    ['CREATE TABLE `users` (id int);', 'mysql'],
    ['CREATE TABLE users (id INT AUTO_INCREMENT PRIMARY KEY);', 'mysql'],
    ['CREATE TABLE users (id NUMBER AUTOINCREMENT, data VARIANT);', 'snowflake'],
    ['CREATE TABLE t (at TIMESTAMP_NTZ);', 'snowflake'],
    ['CREATE OR REPLACE TABLE t (a INT);', 'snowflake'],
    // Snowflake output with NUMBER( is still Snowflake, not Oracle.
    ['CREATE TABLE t (id NUMBER(38,0) AUTOINCREMENT);', 'snowflake'],
    ['CREATE TABLE [dbo].[users] ([id] int);', 'mssql'],
    ['CREATE TABLE users (id INT IDENTITY(1,1) PRIMARY KEY);', 'mssql'],
    ['CREATE TABLE users (name NVARCHAR(50));\nGO', 'mssql'],
    ['CREATE TABLE users (id NUMBER(10) PRIMARY KEY, name VARCHAR2(50));', 'oracle'],
    ['CREATE TABLE users (id serial PRIMARY KEY, tags text[]);', 'postgres'],
    ['CREATE TABLE users (id integer);', 'postgres'],
    // The standard identity clause (PostgreSQL 10+) is not SQL Server's IDENTITY(…).
    ['CREATE TABLE users (id bigint GENERATED BY DEFAULT AS IDENTITY);', 'postgres'],
    ['CREATE TABLE users (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);', 'postgres'],
    // Oracle 12c+: the bare form, which PostgreSQL rejects.
    ['CREATE TABLE "users" ("id" integer GENERATED AS IDENTITY PRIMARY KEY);', 'oracle'],
    ['CREATE TABLE t (id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY);', 'oracle'],
    ['CREATE USER "billing"\nNO AUTHENTICATION\nQUOTA UNLIMITED ON system;', 'oracle'],
    ['', 'postgres'],
  ] as const)('%s → %s', (sql, dialect) => {
    expect(guessDialect(sql)).toBe(dialect);
  });

  it('ignores comments and string literals', () => {
    expect(guessDialect('-- AUTO_INCREMENT in a comment\nCREATE TABLE t (a int);')).toBe(
      'postgres',
    );
    expect(guessDialect("/* VARIANT */ CREATE TABLE t (a text DEFAULT '[x] IDENTITY');")).toBe(
      'postgres',
    );
    expect(stripSqlNoise("a 'it''s' -- c\nb")).toBe("a ''  \nb");
  });

  // What dbdiagram.io (the @dbml/core exporters) and the relvista Snowflake export write for
  // every example: each opens in the import dialog with its own dialect preselected.
  it.each(exampleFiles)('guesses the exporter dialect of %s', (file) => {
    const src = readFileSync(new URL(file, EXAMPLES), 'utf8');
    for (const d of ['postgres', 'mysql', 'mssql', 'oracle'] as const) {
      let sql: string;
      try {
        sql = exporter.export(src, d);
      } catch {
        continue; // records with types a dialect cannot hold (10-records): no export to guess
      }
      const want = d === 'oracle' && PORTABLE_ORACLE.has(file) ? 'postgres' : d;
      expect(guessDialect(sql), `${file} → ${d}`).toBe(want);
    }
    const model = compileDbml(src).model;
    if (model)
      expect(guessDialect(exportSnowflake(model)), `${file} → snowflake`).toBe('snowflake');
  });

  it('recognises .sql file names', () => {
    expect(isSqlName('schema.sql')).toBe(true);
    expect(isSqlName('SCHEMA.SQL')).toBe(true);
    expect(isSqlName('schema.ddl')).toBe(true);
    expect(isSqlName('schema.dbml')).toBe(false);
  });
});
