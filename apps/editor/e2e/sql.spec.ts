/**
 * SQL (design phase3 §6.3): Snowflake export (own generator), SQL export of a multi-file
 * workspace, and opening a .sql file (drop or Open file) in the import dialog with the dialect
 * guessed from its text.
 */
import { expect, test, type Page } from '@playwright/test';
import { installFsMock } from './fsMock.js';
import {
  diagramReady,
  exportItem,
  openEditor,
  openExampleFromPicker,
  trackErrors,
} from './helpers.js';

async function openExample(page: Page, name: RegExp): Promise<void> {
  await page.getByRole('button', { name: 'New', exact: true }).click();
  await page.getByRole('menuitem', { name: 'From example' }).click();
  await page.getByRole('menuitem', { name }).click();
  await diagramReady(page);
}

async function dropFile(page: Page, name: string, text: string): Promise<void> {
  const data = await page.evaluateHandle(
    ([n, t]) => {
      const dt = new DataTransfer();
      dt.items.add(new File([t as string], n as string, { type: 'application/sql' }));
      return dt;
    },
    [name, text] as const,
  );
  const app = page.locator('.ed-app');
  for (const type of ['dragenter', 'dragover', 'drop'])
    await app.dispatchEvent(type, { dataTransfer: data });
}

test('Export ▸ SQL ▸ Snowflake downloads Snowflake DDL', async ({ page }) => {
  const errors = trackErrors(page);
  await openEditor(page);
  await openExample(page, /^E-commerce/);
  const sql = (await exportItem(page, /^SQL/, /Snowflake/)).toString('utf8');
  expect(sql).toContain('Snowflake DDL generated by relvista');
  expect(sql).toContain('CREATE TABLE users (');
  expect(sql).toContain('id INTEGER AUTOINCREMENT PRIMARY KEY');
  expect(sql).toContain('TIMESTAMP_NTZ');
  expect(sql).toMatch(/ALTER TABLE orders ADD CONSTRAINT fk_orders_user FOREIGN KEY/);
  expect(errors).toEqual([]);
});

test('a multi-file workspace exports PostgreSQL and Snowflake from all its files', async ({
  page,
}) => {
  test.setTimeout(120_000);
  const errors = trackErrors(page);
  await openEditor(page);
  await openExampleFromPicker(page, 'Modules \\(folder\\)');
  await diagramReady(page);
  // The SQL menu is enabled for several files now.
  await page.getByRole('button', { name: 'Export' }).click();
  await expect(page.getByRole('menuitem', { name: /^SQL/ })).toBeEnabled();
  await page.keyboard.press('Escape');

  const pg = (await exportItem(page, /^SQL/, /PostgreSQL/)).toString('utf8');
  // Tables from main.dbml, billing.dbml (imported under an alias), common/ and auth.dbml.
  for (const table of ['"user_links"', '"billing_users"', '"invoices"', '"orders"'])
    expect(pg).toContain(`CREATE TABLE ${table}`);
  expect(pg).toMatch(/CREATE TABLE "auth"\."users"/);
  expect(pg).toMatch(/FOREIGN KEY/);

  const sf = (await exportItem(page, /^SQL/, /Snowflake/)).toString('utf8');
  expect(sf).toContain('CREATE SCHEMA IF NOT EXISTS auth;');
  expect(sf).toContain('CREATE TABLE billing_users (');
  expect(errors).toEqual([]);
});

test('dropping a .sql file opens the import dialog with the guessed dialect', async ({ page }) => {
  const errors = trackErrors(page);
  await openEditor(page);
  const mysql =
    'CREATE TABLE `users` (\n  `id` int NOT NULL AUTO_INCREMENT,\n  PRIMARY KEY (`id`)\n);\n';
  await dropFile(page, 'shop.sql', mysql);
  const dialog = page.getByRole('dialog', { name: 'New from SQL' });
  await expect(dialog).toBeVisible();
  const select = dialog.getByRole('combobox', { name: 'Dialect' });
  await expect(select).toHaveValue('mysql');
  await expect(dialog.getByText(/Dialect guessed from the SQL: MySQL/)).toBeVisible();
  await expect(dialog.locator('textarea')).toHaveValue(mysql);
  // The guess can be changed, then the SQL converts into a new document named after the file.
  await select.selectOption('postgres');
  await select.selectOption('mysql');
  await dialog.getByRole('button', { name: 'Convert to DBML' }).click();
  await expect(dialog).toBeHidden({ timeout: 60_000 });
  await expect(page.locator('.ed-filename__name')).toHaveText(/shop\.dbml/);
  await diagramReady(page);
  await expect(page.locator('.rv-canvas')).toContainText('users');

  // A Snowflake file is recognised as Snowflake.
  await dropFile(page, 'wh.sql', 'CREATE TABLE events (id NUMBER AUTOINCREMENT, data VARIANT);');
  await expect(dialog.getByRole('combobox', { name: 'Dialect' })).toHaveValue('snowflake');
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  expect(errors).toEqual([]);
});

test('Open file… accepts a .sql file (no File System Access)', async ({ page }) => {
  await page.addInitScript(installFsMock, 'fallback');
  await openEditor(page);
  const chooser = page.waitForEvent('filechooser');
  await page.keyboard.press('ControlOrMeta+o');
  await (
    await chooser
  ).setFiles({
    name: 'legacy.sql',
    mimeType: 'application/sql',
    buffer: Buffer.from('CREATE TABLE [dbo].[users] ([id] INT IDENTITY(1,1) PRIMARY KEY);'),
  });
  const dialog = page.getByRole('dialog', { name: 'New from SQL' });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('combobox', { name: 'Dialect' })).toHaveValue('mssql');
});
